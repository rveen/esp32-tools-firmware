#!/usr/bin/env python3
"""
ttf2vlw.py  -  Convert a TrueType font into a TFT_eSPI "smooth font" (.vlw)
embedded as a C header (const uint8_t PROGMEM array).

The .vlw format produced here matches what TFT_eSPI's loadFont(const uint8_t[])
expects (big-endian int32 fields):

  Header (6 x int32):
      gCount          number of glyphs
      version         (11, informational)
      yAdvance        font size / line advance (ascent + descent)
      0               reserved
      maxAscent       pixels above baseline
      maxDescent      pixels below baseline

  Per glyph (gCount x 7 x int32), in the same order the bitmaps follow:
      unicode         code point
      height          ink bitmap height (px)
      width           ink bitmap width (px)
      xAdvance        pen advance to next glyph (px)
      dY              ink top above baseline (px, +up)
      dX              left side bearing (px)
      0               reserved

  Bitmap data:
      For each glyph, width*height bytes of 8-bit alpha (anti-aliased coverage),
      concatenated in glyph order.

This is deliberately dependency-light: it only needs Pillow (PIL) with FreeType,
which renders the anti-aliased coverage we embed.

Usage:
    python3 ttf2vlw.py FONT.ttf SIZE_PX OUT.h ARRAY_NAME [--preview OUT.png] [--ascii-only]
"""
import sys
import struct
import argparse
from PIL import Image, ImageDraw, ImageFont

# Default character set: printable ASCII + the Spanish glyphs this UI uses.
SPANISH = "ÁÉÍÓÚÜÑáéíóúüñ¿¡°"
ASCII = "".join(chr(c) for c in range(0x20, 0x7F))


def build(ttf_path, size_px, charset):
    font = ImageFont.truetype(ttf_path, size_px)
    ascent, descent = font.getmetrics()

    glyphs = []  # (unicode, w, h, xadv, dY, dX, alpha_bytes)
    for ch in charset:
        cp = ord(ch)
        xadv = round(font.getlength(ch))
        l, t, r, b = font.getbbox(ch)  # anchor 'la': origin at left/ascender-top
        w, h = r - l, b - t
        if w <= 0 or h <= 0:
            # Whitespace / zero-ink glyph: no bitmap, just an advance.
            glyphs.append((cp, 0, 0, xadv, 0, 0, b""))
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
        dY = ascent - t          # ink top above baseline (+up)
        dX = l                   # left side bearing
        glyphs.append((cp, w, h, xadv, dY, dX, img.tobytes()))

    out = bytearray()
    be = lambda v: struct.pack(">i", v)
    out += be(len(glyphs))
    out += be(11)
    out += be(ascent + descent)
    out += be(0)
    out += be(ascent)
    out += be(descent)
    for cp, w, h, xadv, dY, dX, _ in glyphs:
        out += be(cp)
        out += be(h)
        out += be(w)
        out += be(xadv)
        out += be(dY)
        out += be(dX)
        out += be(0)
    for *_, alpha in glyphs:
        out += alpha
    return bytes(out), (ascent, descent), glyphs


def write_header(path, name, data):
    with open(path, "w") as f:
        f.write("// Auto-generated by tools/ttf2vlw.py - do not edit by hand.\n")
        f.write("// TFT_eSPI smooth font (.vlw) embedded for loadFont(const uint8_t[]).\n")
        f.write("#pragma once\n#include <Arduino.h>\n\n")
        f.write("const uint8_t %s[] PROGMEM = {\n" % name)
        for i in range(0, len(data), 16):
            row = ", ".join("0x%02X" % b for b in data[i:i + 16])
            f.write("  " + row + ",\n")
        f.write("};\n")
        f.write("const uint32_t %s_len = %d;\n" % (name, len(data)))


def preview(path, metrics, glyphs, text):
    """Render `text` using ONLY the emitted metrics + alpha bytes (no TTF),
    so the PNG reflects exactly what the firmware will draw."""
    ascent, descent = metrics
    table = {cp: g for g in glyphs for cp in (g[0],)}
    box_h = ascent + descent
    pen = 0
    for ch in text:
        g = table.get(ord(ch))
        pen += g[3] if g else 0
    img = Image.new("L", (pen + 4, box_h + 4), 0)
    x = 2
    for ch in text:
        g = table.get(ord(ch))
        if not g:
            continue
        cp, w, h, xadv, dY, dX, alpha = g
        if w and h:
            glyph = Image.frombytes("L", (w, h), alpha)
            gx = x + dX
            gy = 2 + ascent - dY
            img.paste(glyph, (gx, gy), glyph)
        x += xadv
    img.save(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("ttf")
    ap.add_argument("size_px", type=int)
    ap.add_argument("out_h")
    ap.add_argument("name")
    ap.add_argument("--preview")
    ap.add_argument("--ascii-only", action="store_true")
    args = ap.parse_args()

    charset = ASCII + ("" if args.ascii_only else SPANISH)
    data, metrics, glyphs = build(args.ttf, args.size_px, charset)
    write_header(args.out_h, args.name, data)
    print("%s: %d glyphs, %d bytes -> %s" % (args.name, len(glyphs), len(data), args.out_h))
    if args.preview:
        preview(args.preview, metrics, glyphs, "ABOUT  Deauth 123!")
        print("preview -> %s" % args.preview)


if __name__ == "__main__":
    main()
